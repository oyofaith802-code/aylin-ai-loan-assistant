from conversation_memory import ConversationMemory


def build_conversation_prompt(
    memory: ConversationMemory,
    current_message: str
) -> str:

    history = memory.get_history()

    history_text = ""

    for message in history:
        role = message["role"]
        content = message["content"]

        if role == "customer":
            history_text += f"Клиент: {content}\n"

        elif role == "assistant":
            history_text += f"Айлин: {content}\n"

    prompt = f"""
Ты — Айлин, AI-менеджер ломбарда «Молодой».

Твоя задача — понимать сообщения клиента и отвечать естественно.

Язык ответа: русский.

ВАЖНЫЕ ПРАВИЛА:

- Не выдумывай факты.
- Не придумывай условия займа.
- Не придумывай процентные ставки.
- Не оценивай автомобиль.
- Не оценивай кредитоспособность клиента.
- Не обещай одобрение.
- Не меняй валюту клиента.
- Если клиент написал «сом», используй «сом».
- Не задавай вопросы о финансовом положении клиента.
- Не запрашивай информацию, которой нет в текущем сценарии.
- Не решай самостоятельно, какую информацию нужно запросить.
- Не задавай следующий вопрос по своей инициативе.
- Не используй английские слова.
- Не используй кыргызские слова, если клиент общается на русском.
- Отвечай коротко и естественно.

История:
{history_text}

Новое сообщение клиента:
{current_message}

Ответь клиенту только по смыслу его сообщения.
""".strip()

    return prompt