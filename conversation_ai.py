import ollama


SYSTEM_PROMPT = """
Ты — Айлин, AI-менеджер ломбарда «Молодой».

Твоя задача — превращать готовую инструкцию системы
в короткое естественное сообщение клиенту.

ОЧЕНЬ ВАЖНО:

Ты НЕ принимаешь бизнес-решения.

Ты НЕ рассчитываешь стоимость автомобиля.

Ты НЕ оцениваешь автомобиль.

Ты НЕ рассчитываешь сумму займа.

Ты НЕ придумываешь условия займа.

Ты НЕ называешь процентные ставки.

Ты НЕ называешь сроки.

Ты НЕ называешь возможную сумму одобрения.

Ты НЕ предполагаешь стоимость автомобиля.

Ты НЕ добавляешь информацию, которой нет
в данных системы или сообщении клиента.

Если система попросила задать конкретный вопрос,
твоя задача — только естественно сформулировать этот вопрос.

Общайся на русском языке.

Если клиент пишет на кыргызском языке,
отвечай на кыргызском.

Отвечай коротко, естественно и вежливо.

Не используй:
- «Вопрос:»
- длинные объяснения;
- заголовки;
- JSON;
- комментарии;
- английские слова без необходимости.

Обычно ответ должен состоять из одного или двух предложений.
"""


def generate_ai_response(
    customer_message: str,
    next_question: str | None = None,
    conversation_history: list | None = None,
    customer_data: dict | None = None
) -> str:

    conversation_history = conversation_history or []
    customer_data = customer_data or {}

    # ---------------------------------------------------------
    # History
    # ---------------------------------------------------------

    history_text = ""

    for item in conversation_history:

        role = item.get("role", "")
        content = item.get("content", "")

        if not content:
            continue

        if role == "customer":
            history_text += f"Клиент: {content}\n"

        elif role == "assistant":
            history_text += f"Айлин: {content}\n"

    if not history_text:
        history_text = "История отсутствует."

    # ---------------------------------------------------------
    # Customer data
    # ---------------------------------------------------------

    customer_data_text = ""

    for key, value in customer_data.items():

        if value is not None:
            customer_data_text += f"{key}: {value}\n"

    if not customer_data_text:
        customer_data_text = "Данные отсутствуют."

    # ---------------------------------------------------------
    # IMPORTANT:
    # System controls the response.
    # ---------------------------------------------------------

    if next_question:

        instruction = f"""
Система требует задать клиенту следующий вопрос:

{next_question}

Сформулируй только этот вопрос естественно.

НЕ отвечай на этот вопрос.

НЕ давай оценку.

НЕ предполагай ответ клиента.

НЕ добавляй никаких чисел,
которых нет в исходном сообщении.

НЕ добавляй никаких условий займа.

Пример:

Система:
Какова примерная стоимость автомобиля?

Хороший ответ:
Какая примерная стоимость вашего автомобиля?

Плохой ответ:
Стоимость вашего автомобиля составляет 450000–550000 сом.
"""

    else:

        instruction = """
Система сообщает, что обязательная информация получена.

Кратко поблагодари клиента.

Не добавляй новые сведения.

Не обещай одобрение займа.
"""

    # ---------------------------------------------------------
    # Prompt
    # ---------------------------------------------------------

    prompt = f"""
{SYSTEM_PROMPT}

ИСТОРИЯ:
{history_text}

ДАННЫЕ КЛИЕНТА:
{customer_data_text}

СООБЩЕНИЕ КЛИЕНТА:
{customer_message}

ИНСТРУКЦИЯ СИСТЕМЫ:
{instruction}

Верни только готовое сообщение Айлин.
"""

    # ---------------------------------------------------------
    # Ollama
    # ---------------------------------------------------------

    response = ollama.chat(
        model="llama3.2:latest",
        messages=[
            {
                "role": "user",
                "content": prompt
            }
        ]
    )

    answer = response["message"]["content"].strip()

    return answer