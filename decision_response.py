def generate_decision_response(
    decision_result: dict,
    customer
) -> str:
    """
    Convert internal business decision into
    a customer-friendly Russian response.
    """

    decision = decision_result.get("decision")

    # ---------------------------------------------------------
    # APPROVED
    # ---------------------------------------------------------

    if decision == "approved":

        loan_amount = customer.loan_amount
        car_value = customer.car_value

        return (
            f"Предварительная проверка вашей заявки пройдена успешно. "
            f"Запрошенная сумма составляет {loan_amount:,.0f} сом, "
            f"примерная стоимость автомобиля — {car_value:,.0f} сом. "
            f"Ваша заявка предварительно одобрена."
        )

    # ---------------------------------------------------------
    # REJECTED
    # ---------------------------------------------------------

    if decision == "rejected":

        errors = decision_result.get("errors", [])

        if "loan_to_value_exceeds_limit" in errors:
            return (
                "К сожалению, на данном этапе заявка не может быть "
                "одобрена, поскольку запрашиваемая сумма превышает "
                "допустимый лимит относительно стоимости автомобиля."
            )

        if "vehicle_too_old" in errors:
            return (
                "К сожалению, данный автомобиль не соответствует "
                "требованиям программы по возрасту транспортного средства."
            )

        if "loan_amount_below_minimum" in errors:
            return (
                "К сожалению, запрашиваемая сумма ниже минимальной "
                "суммы займа по данной программе."
            )

        if "unsupported_loan_program" in errors:
            return (
                "К сожалению, выбранная программа займа сейчас "
                "недоступна для обработки."
            )

        return (
            "К сожалению, заявка не соответствует требованиям "
            "программы займа."
        )

    # ---------------------------------------------------------
    # MANUAL REVIEW
    # ---------------------------------------------------------

    if decision == "manual_review":

        return (
            "Ваша заявка передана на дополнительную проверку "
            "специалистом. После проверки с вами свяжутся."
        )

    # ---------------------------------------------------------
    # UNKNOWN
    # ---------------------------------------------------------

    return (
        "Ваша заявка находится на дополнительной проверке. "
        "Пожалуйста, ожидайте дальнейшей информации."
    )