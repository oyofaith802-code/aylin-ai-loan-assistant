def generate_status_response(status: dict) -> str:

    if not status["found"]:
        return (
            "У вас пока нет зарегистрированной заявки."
        )

    stage = status.get("stage")
    decision = status.get("decision")

    # ---------------------------------------------------------
    # Approved
    # ---------------------------------------------------------

    if decision == "approved":
        return (
            "Ваша заявка предварительно одобрена. "
            "Если потребуется дополнительная информация, "
            "с вами свяжется специалист."
        )

    # ---------------------------------------------------------
    # Rejected
    # ---------------------------------------------------------

    if decision == "rejected":
        return (
            "К сожалению, ваша заявка не была одобрена "
            "по результатам предварительной проверки."
        )

    # ---------------------------------------------------------
    # Manual review
    # ---------------------------------------------------------

    if decision == "manual_review":
        return (
            "Ваша заявка передана на дополнительную "
            "проверку специалистом. После проверки "
            "с вами свяжутся."
        )

    # ---------------------------------------------------------
    # Collecting information
    # ---------------------------------------------------------

    if stage == "collecting_information":
        return (
            "Ваша заявка находится на этапе сбора "
            "необходимой информации."
        )

    # ---------------------------------------------------------
    # Processing
    # ---------------------------------------------------------

    if stage == "processing_application":
        return (
            "Ваша заявка находится на обработке."
        )

    # ---------------------------------------------------------
    # Business decision
    # ---------------------------------------------------------

    if stage == "business_decision":
        return (
            "Ваша заявка находится на этапе "
            "принятия решения."
        )

    # ---------------------------------------------------------
    # New
    # ---------------------------------------------------------

    if stage == "new":
        return (
            "Заявка пока находится на начальном этапе."
        )

    return (
        "Ваша заявка находится в обработке."
    )