import ollama


# ============================================================
# CONFIGURATION
# ============================================================

MODEL_NAME = "llama3.2:latest"


# ============================================================
# SYSTEM PROMPT
# ============================================================

SYSTEM_PROMPT = """
Ты — Айлин, AI-менеджер ломбарда «Молодой».

Твоя задача — превращать готовую инструкцию системы
в короткое естественное сообщение клиенту.

ОЧЕНЬ ВАЖНО:

Ты НЕ принимаешь бизнес-решения.

Ты НЕ рассчитываешь стоимость автомобиля.

Ты НЕ оцениваешь автомобиль.

Ты НЕ рассчитываешь сумму займа.

Ты НЕ придумываешь условия займа.

Ты НЕ называешь процентные ставки.

Ты НЕ называешь сроки.

Ты НЕ называешь возможную сумму одобрения.

Ты НЕ предполагаешь стоимость автомобиля.

Ты НЕ добавляешь информацию, которой нет
в данных системы или сообщении клиента.

Если система попросила задать конкретный вопрос,
твоя задача — только естественно сформулировать этот вопрос.

КРИТИЧЕСКОЕ ПРАВИЛО:

Если система передала следующий вопрос,
ты ОБЯЗАН задать именно этот вопрос.

Не задавай другой вопрос.

Не пропускай вопрос.

Не меняй смысл вопроса.

Не отвечай на вопрос вместо клиента.

Не задавай несколько вопросов одновременно.

Общайся на русском языке.

Если клиент пишет на кыргызском языке,
отвечай на кыргызском.

Отвечай коротко, естественно и вежливо.

Обычно ответ должен состоять из одного предложения.

Не используй:
- «Вопрос:»
- длинные объяснения;
- заголовки;
- JSON;
- комментарии;
- английские слова без необходимости.
"""


# ============================================================
# GENERATE AI RESPONSE
# ============================================================

def generate_ai_response(
    customer_message: str,
    next_question: str | None = None,
    conversation_history: list | None = None,
    customer_data: dict | None = None
) -> str:

    conversation_history = (
        conversation_history or []
    )

    customer_data = (
        customer_data or {}
    )

    # ========================================================
    # HISTORY
    # ========================================================

    history_text = ""

    for item in conversation_history:

        if not isinstance(
            item,
            dict
        ):
            continue

        role = item.get(
            "role",
            ""
        )

        content = item.get(
            "content",
            ""
        )

        if not content:
            continue

        if role == "customer":

            history_text += (
                f"Клиент: {content}\n"
            )

        elif role == "assistant":

            history_text += (
                f"Айлин: {content}\n"
            )

    if not history_text:

        history_text = (
            "История отсутствует."
        )

    # ========================================================
    # CUSTOMER DATA
    # ========================================================

    customer_data_text = ""

    for key, value in customer_data.items():

        if value is not None:

            customer_data_text += (
                f"{key}: {value}\n"
            )

    if not customer_data_text:

        customer_data_text = (
            "Данные отсутствуют."
        )

    # ========================================================
    # SYSTEM INSTRUCTION
    # ========================================================

    if next_question:

        instruction = f"""
Система определила, что клиенту необходимо
предоставить следующую информацию:

{next_question}

Твоя задача:

1. Задать клиенту именно этот вопрос.
2. Можно сделать формулировку немного более естественной.
3. Смысл вопроса должен полностью сохраниться.
4. Не задавай другой вопрос.
5. Не отвечай вместо клиента.
6. Не добавляй новые требования.
7. Не добавляй суммы, проценты или сроки.
8. Не давай оценку автомобиля.
9. Не принимай решение по заявке.
10. Не повторяй информацию, которую уже сообщил клиент.

ПРИМЕР:

Система:
Какого года ваш автомобиль?

Допустимо:
Подскажите, пожалуйста, какого года ваш автомобиль?

Недопустимо:
Какая стоимость вашего автомобиля?

Недопустимо:
Ваш автомобиль стоит 1 500 000 сом?

Недопустимо:
Какую сумму займа вы хотите получить?
"""

    else:

        instruction = """
Система сообщает, что обязательная информация
по заявке собрана.

Кратко сообщи клиенту, что информация получена.

Не принимай решение.

Не обещай одобрение.

Не называй процентную ставку.

Не называй срок.

Не называй сумму одобрения.
"""

    # ========================================================
    # PROMPT
    # ========================================================

    prompt = f"""
{SYSTEM_PROMPT}

ИСТОРИЯ ДИАЛОГА:

{history_text}

ТЕКУЩИЕ ДАННЫЕ КЛИЕНТА:

{customer_data_text}

ПОСЛЕДНЕЕ СООБЩЕНИЕ КЛИЕНТА:

{customer_message}

ИНСТРУКЦИЯ СИСТЕМЫ:

{instruction}

Верни только готовое сообщение Айлин.
"""

    # ========================================================
    # OLLAMA
    # ========================================================

    try:

        response = ollama.chat(
            model=MODEL_NAME,
            messages=[
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT
                },
                {
                    "role": "user",
                    "content": prompt
                }
            ],
            options={
                "temperature": 0
            }
        )

        answer = (
            response["message"]["content"]
            .strip()
        )

    except Exception:

        # Deterministic fallback.
        # The business workflow must continue
        # even if Ollama is unavailable.

        if next_question:

            return next_question

        return (
            "Спасибо, информация получена."
        )

    # ========================================================
    # BASIC CLEANUP
    # ========================================================

    answer = answer.strip()

    answer = answer.replace(
        "Вопрос:",
        ""
    ).strip()

    answer = answer.replace(
        "Вопрос :",
        ""
    ).strip()

    # Remove markdown fences if model produces them.

    if answer.startswith(
        "```"
    ):

        answer = answer.replace(
            "```",
            ""
        ).strip()

    # ========================================================
    # SAFETY FALLBACK
    # ========================================================

    if not answer:

        if next_question:

            return next_question

        return (
            "Спасибо, информация получена."
        )

    return answer